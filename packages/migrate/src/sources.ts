import type { CanonicalModel, MigrationSource } from './schema';

/**
 * What each source lets you move, and the path Atlas recommends. The CLI's
 * `atlas migrate` help, the dashboard wizard and the migration guides are all
 * written from this table, so they agree.
 *
 * `passwords`:
 *   - `export`  the vendor exports password hashes (self-serve or by API) and
 *               Atlas verifies them: users keep their password.
 *   - `ticket`  hashes are exported only through the vendor's support.
 *   - `lazy`    hashes never leave the vendor: use the lazy-migration preset
 *               (Atlas checks the password against the vendor on first sign-in).
 *   - `none`    passwordless source.
 * `bridge`: how the zero-logout bridge recognises an old session — `jwt` (the
 * vendor's session is a JWT checked against its JWKS), `session_table` (opaque
 * session tokens, matched against sessions imported in the bundle) or `none`.
 */
export interface SourceProfile {
  source: MigrationSource;
  label: string;
  /** Models the exporter can produce for this source. */
  models: readonly CanonicalModel[];
  passwords: 'export' | 'ticket' | 'lazy' | 'none';
  /** The lazy-migration preset id, when the vendor can verify a password by API. */
  lazyPreset?: string;
  bridge: 'jwt' | 'session_table' | 'remote' | 'none';
  /** The bridge preset id (`@atlasauth/backend` MIGRATION_BRIDGE_PRESETS). */
  bridgePreset?: string;
  /** How the data is read: the vendor API with the owner's credentials (on their machine), an export file, or the app's own database. */
  exportVia: Array<'api' | 'file' | 'database' | 'support_ticket'>;
  /** One line on what the vendor makes impossible. */
  limits?: string;
}

