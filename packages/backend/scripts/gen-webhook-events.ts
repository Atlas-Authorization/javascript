/**
 * Renders src/webhook-events.generated.ts (the `AtlasWebhookEvent` union) from
 * the server's webhook event schemas. Run by webhook-events.drift.test.ts:
 *
 *   ATLAS_WRITE_GENERATED=1 npx vitest run scripts/webhook-events.drift.test.ts   # rewrite
 *   npx vitest run scripts/webhook-events.drift.test.ts                           # fail on drift
 *
 * Handles the JSON Schema subset those schemas use: type (incl. ['x','null']),
 * const, enum, properties/required, items, additionalProperties, allOf/anyOf/oneOf.
 */

export interface Schema {
  type?: string | string[];
  const?: unknown;
  enum?: unknown[];
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  additionalProperties?: boolean | Schema;
  allOf?: Schema[];
  anyOf?: Schema[];
  oneOf?: Schema[];
  description?: string;
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function doc(description: string | undefined, pad: string): string {
  if (!description) return '';
  return `${pad}/** ${description.replace(/\*\//g, '*\\/').replace(/\s*\n\s*/g, ' ')} */\n`;
}

function objectType(s: Schema, pad: string): string {
  const props = s.properties ?? {};
  const names = Object.keys(props);
  const extra = s.additionalProperties;
  if (names.length === 0) {
    return `Record<string, ${typeof extra === 'object' ? tsType(extra, pad) : 'unknown'}>`;
  }
  const inner = `${pad}  `;
  const required = new Set(s.required ?? []);
  let out = '{\n';
  for (const name of names) {
    const key = IDENT.test(name) ? name : JSON.stringify(name);
    out += doc(props[name]!.description, inner);
    out += `${inner}${key}${required.has(name) ? '' : '?'}: ${tsType(props[name]!, inner)};\n`;
  }
  if (extra !== false) out += `${inner}[key: string]: unknown;\n`;
  return `${out}${pad}}`;
}

export function tsType(s: Schema, pad = ''): string {
  if (s.allOf) return s.allOf.map((x) => tsType(x, pad)).join(' & ');
  const alt = s.anyOf ?? s.oneOf;
  if (alt) return alt.map((x) => tsType(x, pad)).join(' | ');
  if ('const' in s) return JSON.stringify(s.const);
  if (s.enum) {
    const values = s.enum.map((v) => JSON.stringify(v));
    if (Array.isArray(s.type) && s.type.includes('null') && !s.enum.includes(null)) values.push('null');
    return values.join(' | ');
  }
  const types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : s.properties ? ['object'] : [];
  if (types.length === 0) return 'unknown';
  return types
    .map((t) => {
      switch (t) {
        case 'string': return 'string';
        case 'integer':
        case 'number': return 'number';
        case 'boolean': return 'boolean';
        case 'null': return 'null';
        case 'array': {
          const item = s.items ? tsType(s.items, pad) : 'unknown';
          return /^[A-Za-z0-9_]+$/.test(item) ? `${item}[]` : `Array<${item}>`;
        }
        case 'object': return objectType(s, pad);
        default: return 'unknown';
      }
    })
    .join(' | ');
}

/**
 * @param dataSchemas  component name → the `data` schema (WEBHOOK_DATA_SCHEMAS)
 * @param eventData    event name → its data component name (WEBHOOK_EVENT_DATA)
 */
export function renderWebhookEvents(dataSchemas: Record<string, Schema>, eventData: Record<string, string>): string {
  const events = Object.keys(eventData).sort();
  const used = [...new Set(events.map((e) => eventData[e]!))].sort();
  let out =
    '// GENERATED by scripts/gen-webhook-events.ts from the server\'s webhook event schemas. Do not edit by hand.\n' +
    '/* eslint-disable */\n\n';
  for (const name of used) {
    const schema = dataSchemas[name];
    if (!schema) throw new Error(`no data schema ${name}`);
    out += doc(schema.description, '');
    out += `export type ${name} = ${tsType(schema)};\n\n`;
  }
  out +=
    '/** The signed envelope of every delivery: `type` names the event, `data` is its subject. */\n' +
    'export interface AtlasWebhookEnvelope<T extends string, D> {\n' +
    '  /** The event id (also the `atlas-id` header). */\n' +
    '  id: string;\n' +
    '  type: T;\n' +
    '  /** When it was emitted (epoch ms). */\n' +
    '  timestamp: number;\n' +
    '  instance_id: string;\n' +
    '  /** Who caused the event; `system` when no request did. Absent on events recorded before it was added. */\n' +
    '  actor?: { type: "api_key" | "user" | "scim" | "sso" | "system"; id: string | null };\n' +
    '  /** The Idempotency-Key header of the request that caused the event, else null. */\n' +
    '  idempotency_key?: string | null;\n' +
    '  data: D;\n' +
    '}\n\n' +
    '/** Every canonical Atlas webhook event; narrow on `type`. */\n' +
    'export type AtlasWebhookEvent =\n' +
    events.map((e) => `  | AtlasWebhookEnvelope<${JSON.stringify(e)}, ${eventData[e]}>`).join('\n') +
    ';\n\n' +
    'export type AtlasWebhookEventType = AtlasWebhookEvent[\'type\'];\n\n' +
    '/** The event names, sorted. */\n' +
    'export const ATLAS_WEBHOOK_EVENT_TYPES = [\n' +
    events.map((e) => `  ${JSON.stringify(e)},`).join('\n') +
    '\n] as const satisfies readonly AtlasWebhookEventType[];\n';
  return out;
}
