import type { ActionDef } from './emu4-actions-def';

/**
 * TypeScript declarations for a connection action catalog: one entry per provider and action with its input and output
 * types, so `atlas.connections.runAction(id, 'list_issues', input)` can be typed end to end. Generated from the same JSON
 * Schemas Atlas validates with, so the types and the checks cannot disagree.
 */
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (k: string) => (IDENT.test(k) ? k : JSON.stringify(k));
const pad = (n: number) => '  '.repeat(n);

type Schema = Record<string, unknown>;

/** A JSON Schema as a TypeScript type expression (the subset action schemas use). Unknown shapes become `unknown`. */
export function schemaToTs(schema: unknown, depth = 0): string {
  if (typeof schema !== 'object' || schema === null) return 'unknown';
  const s = schema as Schema;
  if (Array.isArray(s.enum) && s.enum.length) return s.enum.map((v) => JSON.stringify(v)).join(' | ');
  const types = Array.isArray(s.type) ? (s.type as string[]) : s.type === undefined ? [] : [String(s.type)];
  if (types.length === 0) return 'unknown';
  return types
    .map((t) => {
      switch (t) {
        case 'string':
          return 'string';
        case 'integer':
        case 'number':
          return 'number';
        case 'boolean':
          return 'boolean';
        case 'null':
          return 'null';
        case 'array':
          return `Array<${schemaToTs(s.items, depth)}>`;
        case 'object': {
          const props = (s.properties ?? {}) as Record<string, Schema>;
          const required = new Set((s.required ?? []) as string[]);
          const names = Object.keys(props);
          if (names.length === 0) return s.additionalProperties === false ? 'Record<string, never>' : 'Record<string, unknown>';
          const lines = names.map((n) => {
            const doc = typeof props[n]?.description === 'string' ? `${pad(depth + 1)}/** ${String(props[n]!.description).replace(/\*\//g, '* /')} */\n` : '';
            return `${doc}${pad(depth + 1)}${key(n)}${required.has(n) ? '' : '?'}: ${schemaToTs(props[n], depth + 1)};`;
          });
          const open = s.additionalProperties === false ? '' : `\n${pad(depth + 1)}[key: string]: unknown;`;
          return `{\n${lines.join('\n')}${open}\n${pad(depth)}}`;
        }
        default:
          return 'unknown';
      }
    })
    .join(' | ');
}

/** The declaration source for a set of actions (any providers). */
export function actionTypesSource(actions: ActionDef[]): string {
  const byProvider = new Map<string, ActionDef[]>();
  for (const a of actions) byProvider.set(a.provider, [...(byProvider.get(a.provider) ?? []), a]);
  const body = [...byProvider.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([provider, list]) => {
      const ops = list
        .sort((a, b) => (a.name < b.name ? -1 : 1))
        .map(
          (a) =>
            `${pad(2)}/** ${a.description.replace(/\*\//g, '* /')} */\n${pad(2)}${key(a.name)}: {\n${pad(3)}input: ${schemaToTs(a.input, 3)};\n${pad(3)}output: ${a.output ? schemaToTs(a.output, 3) : 'unknown'};\n${pad(2)}};`,
        )
        .join('\n');
      return `${pad(1)}${key(provider)}: {\n${ops}\n${pad(1)}};`;
    })
    .join('\n');
  return `// Generated by Atlas from your connection action catalog. Do not edit.\nexport interface ConnectionActionCatalog {\n${body}\n}\n\nexport type ConnectionActionProvider = keyof ConnectionActionCatalog;\nexport type ConnectionActionInput<P extends ConnectionActionProvider, A extends keyof ConnectionActionCatalog[P]> = ConnectionActionCatalog[P][A] extends { input: infer I } ? I : never;\nexport type ConnectionActionOutput<P extends ConnectionActionProvider, A extends keyof ConnectionActionCatalog[P]> = ConnectionActionCatalog[P][A] extends { output: infer O } ? O : never;\n`;
}
