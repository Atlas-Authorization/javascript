// Regenerates src/error-catalog.ts from the API's shared error catalog (status + title only).
// Run in the monorepo: node scripts/sync-error-catalog.mjs. The test suite fails when the copy is stale.
import { readFileSync, writeFileSync } from 'node:fs';

const src = JSON.parse(readFileSync(new URL('../../shared/src/error-catalog.json', import.meta.url), 'utf8'));
const out = Object.fromEntries(Object.entries(src).map(([code, v]) => [code, { status: v.status, title: v.title }]));
writeFileSync(
  new URL('../src/error-catalog.ts', import.meta.url),
  `// Generated by scripts/sync-error-catalog.mjs from the API error catalog. Do not edit.\nexport const ERROR_CATALOG: Record<string, { status: number; title: string }> = ${JSON.stringify(out, null, 2)};\n`,
);
