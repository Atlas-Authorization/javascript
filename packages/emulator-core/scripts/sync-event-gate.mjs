// Regenerates src/event-gate.ts from the webhook catalogue: the events `*` does not cover for older endpoints.
// Run in the monorepo: node scripts/sync-event-gate.mjs. The test suite fails when the copy is stale.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../../core/src/webhooks/events.ts', import.meta.url), 'utf8');
const list = /CANONICAL_WEBHOOK_EVENTS = \[([\s\S]*?)\] as const/.exec(src)?.[1] ?? '';
const names = [...new Set([...list.matchAll(/^\s*'([a-z0-9_.]+)',/gm)].map((m) => m[1]))];
const gateDate = /WILDCARD_GATE_DATE = '([0-9-]+)'/.exec(src)?.[1];
const first = names.indexOf('signing_key.rotated');
if (!gateDate || first < 0) throw new Error('events.ts changed shape: update this script');
writeFileSync(
  new URL('../src/event-gate.ts', import.meta.url),
  `// Generated by scripts/sync-event-gate.mjs from the webhook catalogue. Do not edit.\nexport const WILDCARD_GATE_DATE = '${gateDate}';\nexport const ALL_EVENTS: string[] = ${JSON.stringify(names, null, 2)};\nexport const GATED_EVENTS: string[] = ${JSON.stringify(names.slice(first), null, 2)};\n`,
);
